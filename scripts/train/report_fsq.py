"""Render reports/models/fsq_pair_model.md from the Kaggle kernel's metrics.json.

Usage: python -I scripts/train/report_fsq.py [kaggle/fsq_pair_model/output/metrics.json]
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "scripts" / "eda"))
from common import SERIES, plt  # noqa: E402

src = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "kaggle" / "fsq_pair_model" / "output" / "metrics.json"
m = json.loads(src.read_text())
REP = ROOT / "reports" / "models"
(REP / "figures" / "fsq_pair_model").mkdir(parents=True, exist_ok=True)
t, v = m["test"], m["valid"]
b, c = t["blocking"], t["cluster"]

fig, ax = plt.subplots(figsize=(7.5, 4.0))
ax.plot(t["pr_curve"]["recall"], t["pr_curve"]["precision"], color=SERIES[0])
ax.set_xlabel("recall (of candidate pairs)"); ax.set_ylabel("precision"); ax.set_ylim(0.5, 1.005); ax.set_xlim(0, 1)
ax.set_title("Pair model on unseen places: precision vs recall")
fig.savefig(REP / "figures" / "fsq_pair_model" / "pr_test.png"); plt.close(fig)

pct = lambda x: f"{x:.1%}"  # noqa: E731
L = ["# Pair model benchmark on Foursquare Location Matching", "",
     "Generated by `scripts/train/report_fsq.py` from the Kaggle kernel `kaggle/fsq_pair_model/` "
     f"(CPU, {m['seconds'] / 60:.0f} minutes, LightGBM stopped at {m['best_iteration']} trees).",
     "**Research benchmark only**: the data is under competition terms, so this model is not a shippable artefact. "
     "Its job is to show the stage-2 pair model works at scale on labelled data and to size the cascade.", "",
     "## Setup", "",
     f"- {m['records']:,} POI records of {m['places']:,} real places, worldwide, all categories.",
     "- Places (not records) are split 70 / 10 / 20 into train, validation and test worlds, so the test world holds only unseen places.",
     f"- Blocking inside each world: {m['k_geo']} nearest neighbours by distance, plus records sharing an exact normalised name in the same country.",
     f"- {len(m['features'])} pair features: distance, neighbour rank, six name similarities (character and word TF-IDF, Jaro-Winkler, token set / sort / partial), "
     "address, city, postcode, phone, website domain, category agreement, missing-field count.", "",
     "## Test world results (places never seen in training)", "",
     "| Measure | Value |", "|---|---:|",
     f"| Records / true duplicate pairs | {b['records']:,} / {b['true_pairs']:,} |",
     f"| Candidate pairs after blocking | {b['candidates']:,} ({b['candidates_per_record']:.1f} per record) |",
     f"| Records whose duplicate is reachable through blocking | {pct(b['record_recall_union'])} |",
     f"| Pair model AUC / average precision | {t['auc']:.4f} / {t['average_precision']:.4f} |",
     f"| **Cluster score (competition metric, mean IoU)** | **{c['iou']:.4f}** |",
     f"| B-cubed precision / recall / F1 | {pct(c['b3_precision'])} / {pct(c['b3_recall'])} / {pct(c['b3_f1'])} |",
     f"| Ceiling set by blocking (every reachable true pair accepted) | IoU {t['blocking_ceiling']['cluster_iou']:.4f} |", "",
     "The cluster threshold was chosen on the validation world and applied unchanged to the test world.", "",
     "### Against rule baselines on the same candidates", "",
     "| Method | Cluster IoU | B-cubed precision | B-cubed recall | B-cubed F1 |", "|---|---:|---:|---:|---:|",
     f"| **LightGBM pair model** | **{c['iou']:.4f}** | {pct(c['b3_precision'])} | {pct(c['b3_recall'])} | {pct(c['b3_f1'])} |"]
for k, x in t["baselines"].items():
    L.append(f"| Rule: {k} | {x['cluster_iou']:.4f} | {pct(x['b3']['precision'])} | {pct(x['b3']['recall'])} | {pct(x['b3']['f1'])} |")
best_rule = max(x["cluster_iou"] for x in t["baselines"].values())
L += ["", f"The model beats the best rule by **{c['iou'] - best_rule:+.3f} IoU**. The rules are precise but leave most duplicates unmerged.", "",
      "### Operating points (pair level)", "",
      "| Target | Threshold | Precision | Share of reachable true pairs accepted | Pairs accepted |", "|---|---:|---:|---:|---:|"]
for k, x in t["operating_points"].items():
    if x:
        L.append(f"| {k} | {x['threshold']:.3f} | {pct(x['precision'])} | {pct(x['recall_of_candidates'])} | {x['accepted']:,} |")
L += ["", "![Precision-recall on the test world](figures/fsq_pair_model/pr_test.png)", "",
      "### Travel slice", "", "| Slice (both records) | Candidate pairs | Matches | AUC | Avg precision | Recall at 99% precision |", "|---|---:|---:|---:|---:|---:|"]
for k, x in t["slices"].items():
    L.append(f"| {k} | {x['pairs']:,} | {x['matches']:,} | {x['auc']:.4f} | {x['average_precision']:.4f} | {pct(x['recall_of_candidates_at_precision_0.99'] or 0)} |")
bd = t["confidence_bands"]
L += ["", "### How much the cheap model settles on its own", "",
      "| Band | Share of candidate pairs |", "|---|---:|",
      f"| Rejected with p < 0.02 | {pct(bd['auto_reject_p<0.02'])} |", f"| Accepted with p > 0.98 | {pct(bd['auto_accept_p>0.98'])} |",
      f"| Uncertain, passed to the next stage | {pct(bd['uncertain_0.02-0.98'])} |", "",
      f"So about {pct(1 - bd['uncertain_0.02-0.98'])} of candidate pairs never need an expensive model. "
      "That share is what keeps cross-encoder and LLM cost proportional to hard cases, not to catalogue size.", "",
      "## Feature importance (gain share)", "", "| Feature | Share |", "|---|---:|"]
L += [f"| {f['feature']} | {pct(f['gain_share'])} |" for f in m["feature_importance"][:10]]
L += ["", "## Reading the numbers", "",
      f"- **Blocking is the binding constraint, not the classifier.** Only {pct(b['record_recall_union'])} of duplicate records are reachable, "
      f"which caps the cluster score at {t['blocking_ceiling']['cluster_iou']:.3f}; the model reaches {c['iou']:.3f}. "
      "The next gain comes from a name-embedding candidate generator and a larger neighbour count, before any bigger model.",
      f"- **Pair-level recall looks low ({pct(b['pair_recall_union'])} of true pairs are candidates) because a few places have dozens of records.** "
      "A place with 100 records has 4,950 true pairs and a 10-neighbour search can cover a fraction of them. Clustering closes the rest transitively, "
      "which is why the per-record scores (IoU, B-cubed) are the fair measures.",
      "- **Published context.** Winning entries of the 2022 competition scored about 0.95 IoU with several blocking generators, hundreds of features "
      "and transformer re-rankers (figure from memory of the public leaderboard; confirm before quoting). This single LightGBM is a first stage.",
      f"- **Label noise.** At 99% precision the model accepts {pct(t['operating_points']['precision>=0.99']['recall_of_candidates'])} of reachable true pairs. "
      "The competition labels are known to contain errors, which depresses measured precision at the top of the ranking.",
      f"- Validation world for comparison: IoU {v['cluster']['iou']:.4f}, B-cubed F1 {pct(v['cluster']['b3_f1'])}."]
(REP / "fsq_pair_model.md").write_text("\n".join(L) + "\n", encoding="utf-8")
print("wrote reports/models/fsq_pair_model.md")
